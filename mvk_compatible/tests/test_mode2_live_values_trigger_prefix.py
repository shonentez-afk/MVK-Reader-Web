def _receipt(run, *, capture=True):
    summary=json.loads((run/"summary.json").read_text())
    audit=json.loads((run/AUDIT).read_text())
    w=audit["windows"][0]
    channels=tuple(i in (0,8) for i in range(10))
    spec=tuple(i==0 for i in range(43))
    values=tuple(i in (0,6,35) for i in range(73))
    qt=SimpleNamespace(channels=channels,spec=spec,values=values,
                       start_source_values_ticks=0,end_source_values_ticks=1)
    events=scan_original_values_3100(
        run/"incoming.raw",expected_sha256=summary["raw_sha256"],
        expected_raw_bytes=summary["raw_bytes"],expected_frames=summary["frames_decoded"],
        expected_aux=summary["aux4700_updates"],
        expected_ticks=summary["values_ticks_address_3100"],
        expected_tail_bytes=summary["incomplete_final_frame_bytes"],
        ranges=[(1,0,1)],capture_register_prefix=capture)
    return verify_original_live_values(
        run,summary=summary,source_sha=summary["raw_sha256"],
        qt_values_windows=[(1,qt)],replayed_events=events)


@pytest.fixture
def real_go_run(tmp_path):
    root=os.environ.get("MVK_PREFIX_FIXTURE_DIR")
    if root is None:
        pytest.skip("actual Go prefix fixture is generated by offline CI")
    source=Path(root)/"TEST_2026-11-24_04-00-00.000"
    assert source.is_dir()
    return Path(shutil.copytree(source,tmp_path/source.name))


def test_actual_go_writer_core_accepts_exact_prefix_not_final_image(real_go_run):
    receipt=_receipt(real_go_run)
    assert receipt["verified_events"]==1
    assert receipt["source_trigger_prefix_registers_verified"] is True
    assert receipt["verified_files"][0]["source_raw_layout"]["name"].endswith("RAW_LAYOUT.csv")
    assert receipt["original_delphi_get_value_text_parity_verified"] is False
    event=json.loads((real_go_run/"SOURCE_W01_VALUES_3100_RECEIVED.jsonl").read_text())
    cells=event["source_ordered_raw_tick"]["original_selected_cell_order"]
    assert [x["raw_dword_le_hex"] for x in cells]==[
        "00000040","51000000","0000c03f",None]
    with pytest.raises(ValueError,match="independent trigger-prefix replay"):
        _receipt(real_go_run,capture=False)


def test_actual_go_writer_core_rejects_suffix_even_with_rehashed_evidence(real_go_run):
    run=real_go_run
    audit=json.loads((run/AUDIT).read_text())
    w=audit["windows"][0]
    event_path=run/w["name"]
    event=json.loads(event_path.read_text())
    tick=event["source_ordered_raw_tick"]
    # Valid 3.0 from the *later* descriptor, not the actual trigger.
    tick["original_selected_cell_order"][0]["raw_dword_le_hex"]="00004040"
    raw=(tick["local_source_capture_hh_nn_ss_zzz"]+
         "|RAW_F32_CANDIDATE:00004040|RAW_U32_ADVANCED_UNFORMATTED:51000000"+
         "|RAW_F32_CANDIDATE:0000c03f|UNKNOWN\r\n").encode("ascii")
    tick["source_raw_layout_line_sha256"]=sha256(raw).hexdigest()
    assert parse_source_values_3100_event(event)["raw_line_bytes"]==raw
    payload=(json.dumps(event,separators=(",",":"))+"\n").encode()
    event_path.write_bytes(payload)
    w.update(bytes=len(payload),sha256=sha256(payload).hexdigest())
    (run/w["source_raw_layout_name"]).write_bytes(raw)
    w.update(source_raw_layout_bytes=len(raw),source_raw_layout_sha256=sha256(raw).hexdigest())
    audit_bytes=(json.dumps(audit)+"\n").encode()
    (run/AUDIT).write_bytes(audit_bytes)
    summary=json.loads((run/"summary.json").read_text())
    summary["source_live_values_audit_sha256"]=sha256(audit_bytes).hexdigest()
    (run/"summary.json").write_text(json.dumps(summary))
    with pytest.raises(ValueError,match="differs from RAW trigger prefix"):
        _receipt(run)
