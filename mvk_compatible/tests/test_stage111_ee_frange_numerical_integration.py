def status_for(run):
    raw=json.loads((run/"FIXTURE_STATUS.json").read_text())
    now=datetime.fromisoformat(raw["updated_utc"].replace("Z","+00:00"))
    status=validate_live_status(raw,expected_run=run.name,now=now)
    status["run_directory"]=str(run)
    return status,now


def load_fft(run,status,now):
    req=submit_source_fft_window(run,status,1,1024,
        request_id="00000000000000000000000000000002")
    assert req.source_metadata.factor==4
    assert req.source_metadata.units=="V"
    shutil.copyfile(run/"FIXTURE_FFT.zip",run/RESULT_NAME)
    return req,load_source_long_window(run,status,req,now=now)


def unscaled_preview(preview):
    adc=preview.channels[1]
    a=np.asarray(adc.samples/4,dtype="<f4")
    a.setflags(write=False)
    return replace(preview,input_domain=LEGACY_DOMAIN,channels={
        1:replace(adc,samples=a,sha256=sha256(a.tobytes()).hexdigest(),source_metadata=None)})


def test_actual_go_ring_and_four_spectrum_modes(actual_run):
    status,now=status_for(actual_run)
    req,window=load_fft(actual_run,status,now)
    preview=window.preview
    assert preview.input_domain==METADATA_DOMAIN
    ch=preview.channels[1]
    np.testing.assert_array_equal(ch.samples,np.tile([4.,0.,-4.,0.],256))
    unit1=unscaled_preview(preview)
    for mode in range(4):
        actual=provisional_spectrum(preview,1,mode,n_fft=1024,full_bins=True)
        baseline=provisional_spectrum(unit1,1,mode,n_fft=1024,full_bins=True)
        assert actual["f_range_used"]==4
        expected=np.asarray(baseline["amplitude"])*(1 if mode==0 else 4)
        np.testing.assert_allclose(actual["amplitude"],expected,rtol=2e-6,atol=1e-10)
        bound=bind_live_spectrum_view(preview,1,actual,selected_n=1024,code=0,mode=mode)
        assert bound["unit"]==("дБ","V","V~","V~~")[mode]
    wave=provisional_waveform(preview,1)
    assert wave["peak_m_s2"]==4
    assert wave["unit"]=="V"
    assert wave["live_original_f_range_single"]==4
    status["source_original_storage"]["channels"][0]["source_adc_metadata"]["range_raw_bits"]=0x41000000
    with pytest.raises(ValueError,match="metadata changed"):
        load_source_long_window(actual_run,status,req,now=now)


def test_actual_go_ring_filtered_getsignal_no_double_gain(actual_run):
    status,now=status_for(actual_run)
    req=submit_source_getsignal_envelope_window(actual_run,status,1,9,20,
        request_id="00000000000000000000000000000003")
    assert req.samples==1361 and req.source_metadata.factor==4
    shutil.copyfile(actual_run/"FIXTURE_FIR.zip",actual_run/RESULT_NAME)
    window=load_source_long_window(actual_run,status,req,now=now)
    banks=np.zeros((10,512),dtype="<f4")
    banks[4,0]=1.
    banks[4,1]=.4
    profile=EnvelopeProfile(banks,provenance="SYNTHETIC_QA_NOT_IDP")
    actual=source_live_filtered_getsignal(window,profile,tag=9,code=20)
    legacy=replace(window,request=replace(req,source_metadata=None),
                   preview=unscaled_preview(window.preview))
    baseline=source_live_filtered_getsignal(legacy,profile,tag=9,code=20)
    np.testing.assert_allclose(actual["full_reversed_getsignal"],
        baseline["full_reversed_getsignal"]*4,rtol=2e-6)
    assert actual["rms_m_s2"]==pytest.approx(baseline["rms_m_s2"]*4)
    assert actual["unit"]=="V"


def test_tsxml_reads_accepted_config_at_close_not_latched_range(actual_run,tmp_path):
    summary=json.loads((actual_run/"summary.json").read_text())
    proof=verify_native_live_write_data(actual_run,summary=summary,
                                       source_raw_sha256=summary["raw_sha256"])
    file=proof["verified_channel_files"][0]
    meta=file["source_close_adc_metadata"]
    assert meta["effective_gain"]==9 and meta["units"]=="A"
    target=tmp_path/"out";target.mkdir()
    shutil.copyfile(actual_run/file["name"],target/file["name"])
    out=write_verified_source_tsxml_sidecars(target,live_proof=proof,
            source_run_end_utc=summary["ended_utc"])
    assert out[0]["sidecar_created"]
    node=ET.parse(target/out[0]["name"])
    assert node.findtext(".//InternalChannelGain")=="9"
    assert node.findtext(".//Units")=="A"
    assert sha256((target/file["name"]).read_bytes()).hexdigest()==file["sha256"]


def test_source_metadata_strict_and_zero():
    meta=dict(socket_epoch=1,from_descriptor=True,range_raw_bits=0,
              range_current_socket=True,units_known=False,units="",
              units_current_socket=False)
    m=parse_source_adc_metadata(meta)
    assert m.factor==1 and source_derived_units(m,1)=="ед. неизвестны"
    for patch in (dict(range_raw_bits=True),dict(range_raw_bits=0x7f800000),
                  dict(range_raw_bits=0xbf800000),dict(units="V"),dict(socket_epoch=0)):
        with pytest.raises(ValueError):
            parse_source_adc_metadata({**meta,**patch})
