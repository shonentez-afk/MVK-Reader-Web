@pytest.fixture
def latch_run(tmp_path):
    root = os.environ.get("MVK_TACH_LATCH_FIXTURE_DIR")
    if not root:
        pytest.skip("actual Go fixture generated by cross-language CI")
    source = Path(root) / "TEST_2026-11-24_09-45-00.000"
    assert source.is_dir()
    return Path(shutil.copytree(source, tmp_path / source.name))


def _receipt(run, *, gate=True):
    s = json.loads((run / "summary.json").read_text())
    qt = SimpleNamespace(channels=tuple(i in (8,9) for i in range(10)),
                         spec=(False,)*43, values=tuple(i==35 for i in range(73)),
                         start_source_values_ticks=1, end_source_values_ticks=4)
    events = scan_original_values_3100(
        run/"incoming.raw", expected_sha256=s["raw_sha256"],
        expected_raw_bytes=s["raw_bytes"], expected_frames=s["frames_decoded"],
        expected_aux=s["aux4700_updates"], expected_ticks=s["values_ticks_address_3100"],
        expected_tail_bytes=s["incomplete_final_frame_bytes"], ranges=[(1,1,4)],
        param_gate_path=run/SOURCE_PARAM_GATE_NAME,
        expected_param_gate_sha256=s["source_original_param_gate_sha256"],
        expected_param_gate_records=s["source_original_param_gate_records"],
        expected_frozen_param_frames=s["source_original_param_frames_skipped_frozen"],
        expected_frozen_values=s["source_original_values_3100_skipped_frozen"],
        capture_register_prefix=True,
        tach_gate_path=run/SOURCE_TACH_GATE_NAME if gate else None,
        expected_tach_gate_sha256=s["source_original_tach_gate_sha256"] if gate else None,
        expected_tach_gate_records=s["source_original_tach_gate_records"] if gate else 0)
    return verify_original_live_values(run, summary=s, source_sha=s["raw_sha256"],
        qt_values_windows=[(1,qt)], replayed_events=events)


def test_go_tach_latch_reset_before_suffix_and_raw_replay(latch_run):
    receipt = _receipt(latch_run)
    assert receipt["verified_events"] == 3
    assert receipt["source_tach_latch_replay_verified"] is True
    assert receipt["source_trigger_prefix_registers_verified"] is True
    assert receipt["original_delphi_get_value_text_parity_verified"] is False
    with pytest.raises(ValueError, match="latch mode"):
        _receipt(latch_run, gate=False)


@pytest.mark.parametrize("offset,xor", [(25,2),(8,3),(32,1)])
def test_rehashed_tach_admission_still_must_match_frame_and_epoch(latch_run,offset,xor):
    path = latch_run/SOURCE_TACH_GATE_NAME
    b = bytearray(path.read_bytes())
    b[offset] ^= xor
    path.write_bytes(b)
    p = latch_run/"summary.json"
    s = json.loads(p.read_text())
    s["source_original_tach_gate_sha256"] = sha256(b).hexdigest()
    p.write_text(json.dumps(s))
    with pytest.raises(ValueError, match="TACH gate: admission contradicts"):
        _receipt(latch_run)


def test_rehashed_wrong_derived_latch_is_rejected(latch_run):
    audit_path = latch_run/AUDIT
    audit = json.loads(audit_path.read_text())
    w = audit["windows"][0]
    event_path = latch_run/w["name"]
    rows = [json.loads(line) for line in event_path.read_bytes().splitlines()]
    tick = rows[0]["source_ordered_raw_tick"]
    tick["original_selected_cell_order"][0]["raw_dword_le_hex"] = "2a000000"
    layout = latch_run/w["source_raw_layout_name"]
    raw = layout.read_bytes().splitlines(keepends=True)
    raw[0] = raw[0].replace(b"01000000", b"2a000000", 1)
    tick["source_raw_layout_line_sha256"] = sha256(raw[0]).hexdigest()
    data = b"".join((json.dumps(row,separators=(",",":"))+"\n").encode() for row in rows)
    event_path.write_bytes(data)
    w.update(bytes=len(data),sha256=sha256(data).hexdigest())
    layout.write_bytes(b"".join(raw))
    w.update(source_raw_layout_bytes=sum(map(len,raw)),source_raw_layout_sha256=sha256(b"".join(raw)).hexdigest())
    blob = (json.dumps(audit)+"\n").encode()
    audit_path.write_bytes(blob)
    p = latch_run/"summary.json"
    s = json.loads(p.read_text())
    s["source_live_values_audit_sha256"] = sha256(blob).hexdigest()
    p.write_text(json.dumps(s))
    with pytest.raises(ValueError, match="differs from RAW trigger prefix"):
        _receipt(latch_run)
